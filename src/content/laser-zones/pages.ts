export const LASER_ZONE_PAGES = [bikiniPage, podmyshkiPage, nogiPage, litsoPage, rukiPage, muzhskayaPage] as const;

/** Страница зоны по slug услуги — для редиректа со старых адресов /services/laser-*. */
export function zonePagePathForService(serviceSlug: string) {
  // Порядок важен: сначала специализированные страницы, мужская — для зон тела.
  const order = [bikiniPage, podmyshkiPage, nogiPage, litsoPage, rukiPage, muzhskayaPage];
  return order.find((page) => (page.zones as readonly string[]).includes(serviceSlug))?.content.path ?? null;
}

