function isStringArray(value: unknown): value is string[] {
  return Array.isArray(value) && value.every((item) => typeof item === "string");
}

export function parseLegalContent(value: string): LegalContent | null {
  try {
    const parsed = JSON.parse(value) as Partial<LegalContent>;
    if (typeof parsed.lead !== "string" || !Array.isArray(parsed.sections)) return null;
    const sections = parsed.sections.filter(
      (section): section is LegalContentSection =>
        Boolean(section) &&
        typeof section.title === "string" &&
        (section.paragraphs === undefined || isStringArray(section.paragraphs)) &&
        (section.items === undefined || isStringArray(section.items))
    );
    return sections.length === parsed.sections.length ? { lead: parsed.lead, sections } : null;
  } catch {
    return null;
  }
}

function replaceTokens(value: string, operator: LegalOperator): string {
  const replacements: Record<string, string> = {
    clinicName: operator.clinicName,
    legalName: operator.legalName,
    taxId: operator.taxId,
    address: operator.address,
    phone: operator.phone,
    email: operator.email
  };
  return value.replace(/\{\{(\w+)\}\}/g, (_, key: string) => replacements[key] ?? "");
}

export function resolveLegalContent(value: string, operator: LegalOperator): LegalContent | null {
  const content = parseLegalContent(value);
  if (!content) return null;
  return {
    lead: replaceTokens(content.lead, operator),
    sections: content.sections.map((section) => ({
      title: replaceTokens(section.title, operator),
      paragraphs: section.paragraphs?.map((paragraph) => replaceTokens(paragraph, operator)),
      items: section.items?.map((item) => replaceTokens(item, operator))
    }))
  };
}

export function serializeLegalContent(content: LegalContent): string {
  return JSON.stringify(content);
}
